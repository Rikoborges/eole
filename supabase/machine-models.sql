-- Ajoute une colonne « famille » (code CA0…) à la table printer_models et y
-- charge 248 modèles (désignation + famille + marque). Les modèles déjà
-- présents dans la table sont conservés : rien n'est supprimé.
--
-- À lancer APRÈS supabase/printer-models.sql (la table doit exister).
-- Idempotent : peut être relancé sans créer de doublon.
--
-- Nettoyage fait sur la liste reçue (253 lignes) :
--   - 5 lignes en double retirées (IRAC3822 REC, IRAC3826 REC,
--     IRAC3826 REC + FIN.EXT, IRAC3830 REC, TASK 6053CI REC + FIN.EXT)
--   - marque corrigée pour des désignations Sharp notées CANON :
--   SHA BP50C26 REC + FIN.EXT (CA010687) : CANON -> SHARP
--   SHA BP50C31 REC + FIN.EXT (CA010686) : CANON -> SHARP
--   SHA BP70C36 REC + FIN.EXT (CA010688) : CANON -> SHARP
--   SHA BP70C65 REC + FIN.EXT (CA010689) : CANON -> SHARP
--
-- À confirmer avec l'atelier (laissé tel quel) :
--   - IRAC5870 REC + FIN EXT (CA009613) et IRAC5870 REC + FIN.EXT (CA010690)
--     semblent être le même modèle avec deux codes
--   - « FIN EXT » sans point sur 6 désignations, « SHA BP55C26 + FIN.EXT » sans REC
-- ============================================================================

